enum class AppLanguage(val code: String, val label: String) {
    ENGLISH("EN", "English"),
    HINDI("HI", "हिन्दी");

    companion object {
        fun fromCode(code: String?): AppLanguage =
            entries.firstOrNull { it.code.equals(code, ignoreCase = true) } ?: ENGLISH
    }
}

